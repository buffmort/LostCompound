namespace LostCompound.Tools
{
    /// <summary>
    /// 全局 debug 开关（主菜单与战斗内**共用同一份**状态）。
    ///
    /// 为什么要有它（修的是一个真 bug）：
    ///   原先主菜单（GameLobby._debug）与战斗内（Player._debug）各存了一份开关，
    ///   两份状态互不相通，而且**战斗内那份从来没有任何地方读它**——
    ///   于是 127（超雄）/128（解锁全部配方）/129（当场拿道具）不输 255 也能用，
    ///   255 那句「你已进入debug模式!」是张空头支票。
    ///   现在开关只有这一份静态状态，两边读同一个值：
    ///     主菜单输 255 → 进游戏后战斗里的 127/128/129 立刻可用（菜单里也会多出调试项）；
    ///     战斗中输 255 → 退回主菜单后同样多出调试项。
    ///   同一次进程运行内**持久有效**：不随回合、也不随战斗结束而失效。
    ///
    /// 为什么用 static 而不是把开关对象注入两边：主菜单与战斗循环之间没有公共持有者
    ///   （GameLobby 是临时对象、Player 每局 new 一个、DebugMenu 是静态类），
    ///   唯一两边都能看到的位置就是静态状态。进程生命周期 = 开关生命周期，
    ///   与「调试开关」的语义相符（重启游戏即回到关闭）。
    ///
    /// 为什么只有「打开」没有「关闭」：改造前两条 255 入口本来就只负责开，
    ///   顺手加一个关闭 API 只会多出「谁在什么时候关掉了调试」的新状态问题；
    ///   真需要重置，重启进程即可。
    /// </summary>
    public static class DebugState
    {
        /// <summary>是否已进入 debug 模式（默认关闭）。</summary>
        public static bool Enabled { get; private set; }

        /// <summary>
        /// 打开 debug 开关。主菜单的 255 与战斗内的 255 都走这一个入口，
        /// 保证「两边开的是同一个开关」而不是各开各的。
        /// </summary>
        public static void Enable() => Enabled = true;
    }
}
